/**
 * Generate a compact share code for a preset (base64 encoded JSON)
 */
export function generatePresetShareCode(preset: FilterPreset): string {
  const payload = {
    _app: 'lumina_preset_v1',
    name: preset.name,
    category: preset.category,
    description: preset.description,
    gradient: preset.thumbnailGradient,
    settings: preset.settings,
    hsl: preset.hsl,
    toneCurves: preset.toneCurves,
    tags: preset.tags,
    author: preset.author || 'Lumina Creator',
    created: Date.now(),
  };

  try {
    const jsonStr = JSON.stringify(payload);
    return `LUMINA_${btoa(unescape(encodeURIComponent(jsonStr)))}`;
  } catch (e) {
    return `LUMINA_${btoa(JSON.stringify(payload))}`;
  }
}

/**
 * Parse and validate a preset share code
 */
export function parsePresetShareCode(code: string): FilterPreset | null {
  try {
    let clean = code.trim();
    if (clean.startsWith('LUMINA_')) {
      clean = clean.replace('LUMINA_', '');
    }

    const jsonStr = decodeURIComponent(escape(atob(clean)));
    const parsed = JSON.parse(jsonStr);

    if (!parsed.name || !parsed.settings) {
      return null;
    }

    const preset: FilterPreset = {
      id: `imported_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      name: parsed.name,
      category: parsed.category || 'Custom',
      description: parsed.description || 'Imported via share code',
      thumbnailGradient: parsed.gradient || 'from-indigo-600 to-purple-600',
      settings: parsed.settings || {},
      hsl: parsed.hsl,
      toneCurves: parsed.toneCurves,
      tags: parsed.tags || ['imported'],
      author: parsed.author,
      createdAt: parsed.created || Date.now(),
      shareCode: code,
    };

    return preset;
  } catch (err) {
    console.error('Failed to parse share code:', err);
    return null;
  }
}

/**
 * Export preset as JSON file download
 */
export function exportPresetAsJsonFile(preset: FilterPreset) {
  const data = JSON.stringify(preset, null, 2);
  const blob = new Blob([data], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${preset.name.replace(/[^a-zA-Z0-9_-]/g, '_')}_LuminaPreset.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

