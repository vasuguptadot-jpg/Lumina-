export function getPresetById(id: string | null | undefined, customPresets: FilterPreset[] = []): FilterPreset | undefined {
  if (!id) return undefined;
  return (
    customPresets.find((p) => p.id === id) ||
    MARKETPLACE_PRESETS.find((p) => p.id === id) ||
    FILTER_PRESETS.find((p) => p.id === id)
  );
}

export function getAllPresets(customPresets: FilterPreset[] = []): FilterPreset[] {
  return [...customPresets, ...MARKETPLACE_PRESETS, ...FILTER_PRESETS];
}

export function searchPresets(
  query: string,
  category: string = 'All',
  customPresets: FilterPreset[] = [],
  favoritesOnly: boolean = false,
  favoriteIds: string[] = []
): FilterPreset[] {
  const all = getAllPresets(customPresets);
  const q = query.trim().toLowerCase();

  return all.filter((p) => {
    if (favoritesOnly && !favoriteIds.includes(p.id)) return false;

    if (category !== 'All') {
      if (category === 'Custom' && !customPresets.some((cp) => cp.id === p.id)) {
        return false;
      }
      if (category === 'Marketplace' && !p.isCommunity) {
        return false;
      }
      if (category !== 'Custom' && category !== 'Marketplace' && p.category !== category) {
        return false;
      }
    }

    if (!q) return true;

    const nameMatch = p.name.toLowerCase().includes(q);
    const descMatch = p.description.toLowerCase().includes(q);
    const tagMatch = p.tags?.some((t) => t.toLowerCase().includes(q));
    const catMatch = p.category.toLowerCase().includes(q);
    const authorMatch = p.author?.toLowerCase().includes(q);

    return nameMatch || descMatch || tagMatch || catMatch || authorMatch;
  });
}

